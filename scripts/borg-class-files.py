#!/usr/bin/env python3
"""borg-reborn-rs (#520): the per-class borg files.

`harness/borg.txt` is the common file. `harness/borg_<class>.txt` holds the
settings that differ for one class, as plain lines:

    borg_param_town_heal_reserve_hp_percent = 300
    borg_town_w_heal = 150

A `borg_param_*` line is a parameter (params.rs); any other `borg_*` line is
one of the core's borg.txt settings (`BORG_SETTINGS`, borg_init.rs), read per
class since the second half of #520. The keys the shell reads itself
(`borg_reborn_*`, `borg_plan`, `borg_scary_list`) and the respawn settings
(`borg_respawn_*`, which pick the next character) have no class value.

The core reads one borg.txt per run (and the zoo's adapter copies only that
file, docs/ZOO-INTERFACE.md), so the class files are folded into
`harness/borg.txt` as a generated block of class lines. A line of a family
that had per-class parameters before #520 is written under its old name (the
alias the parser keeps, so a zoo profile naming that key still rewrites it);
any other is written as `borg_param_<name>@<class> = <value>`, and a
`borg_*` setting as `borg_<name>@<class> = <value>`.

    scripts/borg-class-files.py fold    rewrite the block in harness/borg.txt
    scripts/borg-class-files.py check   fail if the block is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HARNESS = ROOT / 'harness'
BORG_TXT = HARNESS / 'borg.txt'
CLASSES = ['warrior', 'mage', 'druid', 'priest', 'necromancer', 'paladin', 'rogue', 'ranger', 'blackguard']
BEGIN = '# ---- BEGIN CLASS FILES (generated by scripts/borg-class-files.py from harness/borg_<class>.txt; do not edit) ----'
END = '# ---- END CLASS FILES ----'
LINE = re.compile(r'^borg_param_([a-z0-9_]+)\s*=\s*(-?\d+)\s*$')
SETTING = re.compile(r'^(borg_[a-z0-9_]+)\s*=\s*([A-Za-z0-9-]+)\s*$')
SHELL_KEYS = re.compile(r'^borg_(reborn_[a-z0-9_]+|plan|scary_list|respawn_[a-z0-9_]+)$')


def core_settings():
    """The core's borg.txt settings (`BORG_SETTINGS`, borg_init.rs), name -> kind
    ('i' an integer, 'b' true/false). The table's rows read `    i(c"name", default),`
    or `    b(...)`; update this pattern if the table's format changes (a name it
    cannot find is refused, never folded)."""
    text = (ROOT / 'borg-core/src/borg_init.rs').read_text()
    return {name: kind for kind, name in re.findall(r'^    ([ib])\(c"(borg_[a-z0-9_]+)"', text, re.M)}


BOOL_WORDS = {'TRUE', 'FALSE', 'YES', 'NO', 'T', 'F', 'Y', 'N', '1', '0'}


def value_ok(kind, value):
    """The core's strict class-line value (`class_setting_line`): exactly an
    integer for an int setting, one of the true/false words for a bool one."""
    if kind == 'b':
        return value.upper() in BOOL_WORDS
    return re.fullmatch(r'-?[0-9]+', value) is not None and -2**31 <= int(value) < 2**31


def legacy_name(name, cls):
    """The pre-#520 per-class parameter name of a folded family, else None."""
    m = re.fullmatch(r'attack_preference_([a-z]+)_permille', name)
    if m:
        return f'attack_preference_{cls}_{m.group(1)}_permille'
    if name in ('attack_arrow_point_blank_divisor', 'town_heal_curve_scale_percent', 'town_heal_reserve_hp_percent'):
        return f'{name}_{cls}'
    return None


def class_lines(cls, text):
    out = []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        m = LINE.match(line)
        if not m:
            s = SETTING.match(line)
            if not s or s.group(1).startswith('borg_param_'):
                raise SystemExit(f'harness/borg_{cls}.txt:{n}: expected "borg_param_<name> = <integer>" '
                                 f'or "borg_<setting> = <value>", got {raw!r}')
            if SHELL_KEYS.match(s.group(1)):
                raise SystemExit(f'harness/borg_{cls}.txt:{n}: {s.group(1)} has no class value '
                                 '(the shell reads it from borg.txt only, or it picks the next character)')
            kind = core_settings().get(s.group(1))
            if kind is None:
                raise SystemExit(f'harness/borg_{cls}.txt:{n}: {s.group(1)} is no borg.txt setting of the core '
                                 '(BORG_SETTINGS in borg-core/src/borg_init.rs; a retired setting has no class value)')
            if not value_ok(kind, s.group(2)):
                want = 'TRUE/FALSE/YES/NO/T/F/Y/N/1/0' if kind == 'b' else 'an integer'
                raise SystemExit(f'harness/borg_{cls}.txt:{n}: {s.group(1)} = {s.group(2)}: the value must be {want}')
            out.append(f'{s.group(1)}@{cls} = {s.group(2)}')
            continue
        name, value = m.groups()
        if '@' in name:
            raise SystemExit(f'harness/borg_{cls}.txt:{n}: a class file names no class ({raw!r})')
        legacy = legacy_name(name, cls)
        out.append(f'borg_param_{legacy} = {value}' if legacy else f'borg_param_{name}@{cls} = {value}')
    return out


def block():
    lines = [BEGIN,
             '# The settings of harness/borg_<class>.txt that override the common ones',
             '# for one class (#520). Edit the class files and run',
             '# scripts/borg-class-files.py fold.']
    for cls in CLASSES:
        path = HARNESS / f'borg_{cls}.txt'
        if not path.exists():
            continue
        body = class_lines(cls, path.read_text())
        if body:
            lines.append(f'# {cls} (harness/borg_{cls}.txt)')
            lines.extend(body)
    lines.append(END)
    return '\n'.join(lines) + '\n'


def folded(text):
    """borg.txt with the block replaced, or inserted before the formula section
    (else at the end) when absent."""
    begins, ends = text.count(BEGIN), text.count(END)
    if (begins, ends) not in ((0, 0), (1, 1)) or (begins and text.index(END) < text.index(BEGIN)):
        raise SystemExit('harness/borg.txt: the CLASS FILES block is damaged (its BEGIN/END markers); '
                         'delete what is left of it and run scripts/borg-class-files.py fold')
    if begins:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END) + 1
        return text[:a] + block() + text[b:]
    marker = '[BEGIN FORMULA SECTION]'
    if marker in text:
        a = text.index(marker)
        return text[:a] + block() + '\n\n' + text[a:]
    return text.rstrip('\n') + '\n\n' + block()


def main(argv):
    if len(argv) != 2 or argv[1] not in ('fold', 'check'):
        raise SystemExit(__doc__)
    text = BORG_TXT.read_text()
    new = folded(text)
    if argv[1] == 'fold':
        BORG_TXT.write_text(new)
    elif new != text:
        raise SystemExit('harness/borg.txt: the class-file block is out of date; run scripts/borg-class-files.py fold')


if __name__ == '__main__':
    main(sys.argv)

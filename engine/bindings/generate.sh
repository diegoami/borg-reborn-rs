#!/usr/bin/env bash
# Generate the Rust Borg's engine bindings (docs/SPEC.md §3.4).
#   engine/bindings/generate.sh            write borg-reborn-rs/src/bindings.rs
#   engine/bindings/generate.sh --check    regenerate and fail if it differs
# From the pristine headers of engine/angband/src (the patch series changes
# no header the bindings use), with bindgen and libclang. Only the
# allowlisted symbols are kept; they are the reads of docs/ENGINE-READS.md.
# inkey_hack is declared in no header (ui-input.c:130 defines it), so
# engine.rs declares it itself.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/borg-reborn-rs/src/bindings.rs"
BINDGEN_VERSION=0.73.2
have="$(bindgen --version 2>/dev/null | awk '{print $2}')"
[ "$have" = "$BINDGEN_VERSION" ] || {
    echo "generate.sh: bindgen $BINDGEN_VERSION needed (have '${have:-none}'): cargo install bindgen-cli --version $BINDGEN_VERSION --locked" >&2; exit 2; }

FUNCTIONS='map_info|square_in_bounds_fully|square_object|square_isvault|square_iswebbed|square_shopnum|cave_monster|cmd_get_nrepeats|get_com|option_set|spell_by_index|store_stock_list|price_item|Term_inkey|object_desc|object_flags_known|object_flavor_is_aware|object_fully_known|object_runes_known|object_weight_one|pack_slots_used|square|monster_is_visible|feat_is_shop|panel_contains|equipped_item_slot|object_is_in_quiver'
VARS='cave|player|turn|z_info|Rand_quick|Rand_value|state_i|STATE|Term|row_top_map|row_bottom_map|col_map|tile_width|tile_height|r_info|k_info|e_info|a_info|classes|races|stores|extract_energy|adj_str_blow|adj_str_hold|f_info|bodies|inkey_flag'
ITEMS='TMD_.*|FEAT_FLOOR|OPT_birth_percent_damage|OBJ_NOTICE_IGNORE|ODESC_FULL|ODESC_STORE|EVT_KBRD|EVT_NONE|EVT_DISCONNECT|ui_event|keypress'

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
    echo "//! The engine's C declarations the Rust Borg uses, generated by bindgen"
    echo "//! $BINDGEN_VERSION from upstream Angband e473720's headers"
    echo "//! (engine/bindings/generate.sh, docs/SPEC.md §3.4). Do not edit: change"
    echo "//! the allowlist and regenerate. Only engine.rs uses them."
    echo
    bindgen "$ROOT/engine/bindings/wrapper.h" \
        --allowlist-function "^($FUNCTIONS)\$" \
        --allowlist-var "^($VARS)\$" \
        --allowlist-item "^($ITEMS)\$" \
        --default-enum-style consts \
        --no-prepend-enum-name \
        --translate-enum-integer-types \
        --no-doc-comments \
        --use-core \
        --ctypes-prefix core::ffi \
        --rust-target 1.82 \
        -- -I"$ROOT/engine/angband/src" -DALLOW_BORG -std=gnu99 2>/dev/null |
    # Anonymous enums get numbered type names (_bindgen_ty_N) whose numbers
    # change with the libclang version: use their integer type instead, so
    # every libclang gives the same file.
    python3 -c '
import re, sys
text = sys.stdin.read()
types = dict(re.findall(r"^pub type (_bindgen_ty_\d+) = (\S+);\n", text, re.M))
text = re.sub(r"^pub type _bindgen_ty_\d+ = \S+;\n", "", text, flags=re.M)
text = re.sub(r"\b_bindgen_ty_\d+\b", lambda m: types.get(m.group(0), m.group(0)), text)
sys.stdout.write(text)
'
} > "$tmp"
if [ "${1:-}" = --check ]; then
    cmp -s "$tmp" "$OUT" || {
        diff -u "$OUT" "$tmp" | head -60 >&2
        echo "generate.sh: borg-reborn-rs/src/bindings.rs is not what the headers generate (libclang $(clang --version 2>/dev/null | head -1)); run engine/bindings/generate.sh" >&2
        exit 1; }
    echo "bindings: up to date"
else
    cp "$tmp" "$OUT"
    echo "wrote $OUT ($(wc -l < "$OUT") lines)"
fi
